import PDFDocument from "pdfkit";
import type { CampaignPlan } from "./planner.js";
import { zonedDate } from "@radiohost/shared";

export interface ProposalData {
  stationName: string;
  advertiser: string;
  startDate: string;
  endDate: string;
  spotsPerDay: number;
  ruleLabel: string;
  ratePerSpot: number;
  currency: string;
  plan: CampaignPlan;
}

/** Generates a branded proposal PDF as a Buffer. */
export function proposalPdf(data: ProposalData): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 48, size: "A4" });
    const chunks: Buffer[] = [];
    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    // Header band
    doc.rect(0, 0, doc.page.width, 90).fill("#1e293b");
    doc
      .fill("#ffffff")
      .font("Helvetica-Bold")
      .fontSize(22)
      .text(data.stationName, 48, 30);
    doc
      .font("Helvetica")
      .fontSize(11)
      .text("Advertising proposal", 48, 60);

    doc
      .fill("#0f172a")
      .font("Helvetica-Bold")
      .fontSize(18)
      .text("Sponsorship proposal", 48, 120);

    doc
      .font("Helvetica")
      .fontSize(11)
      .fill("#334155")
      .text(
        `Prepared for ${data.advertiser}\n` +
          `Campaign period: ${data.startDate}  to  ${data.endDate}\n` +
          `Schedule: ${data.ruleLabel} · ${data.spotsPerDay} spots per day`,
        { lineGap: 4 },
      );

    // Summary table
    const summaryY = 240;
    doc.rect(48, summaryY, doc.page.width - 96, 150).fill("#f8fafc").stroke("#e2e8f0");
    doc.fill("#0f172a").font("Helvetica-Bold").fontSize(12);
    doc.text("Deliverables", 68, summaryY + 16);
    doc.font("Helvetica").fontSize(11).fill("#334155");
    const rows: [string, string][] = [
      ["Airings", `${data.plan.expectedSpots}`],
      ["Campaign days", `${data.plan.days}`],
      ["Rate per spot", `${data.currency} ${data.ratePerSpot.toFixed(2)}`],
      ["Total value", `${data.currency} ${data.plan.totalValue.toFixed(2)}`],
    ];
    let y = summaryY + 42;
    for (const [label, value] of rows) {
      doc.fill("#475569").text(label, 68, y, { width: 220 });
      doc.fill("#0f172a").text(value, 320, y, { width: 220, align: "right" });
      y += 24;
    }

    doc
      .fill("#0f172a")
      .font("Helvetica-Bold")
      .fontSize(12)
      .text("What you get", 48, summaryY + 180);
    doc.font("Helvetica").fontSize(11).fill("#334155");
    doc.text(
      "• Airtime on every eligible break, capped to your booked volume\n" +
        "• Proof of every airing, with the audience at the time of each spot\n" +
        "• A delivery summary reconciling booked vs delivered airtime\n" +
        "• No same advertiser twice in a row — your campaign always opens a break",
      48, summaryY + 208, { lineGap: 6 },
    );

    doc
      .fill("#64748b")
      .fontSize(9)
      .text(
        `Generated by RadioHost Studio · ${zonedDate(Date.now(), "UTC")}`,
        48,
        doc.page.height - 60,
      );

    doc.end();
  });
}
